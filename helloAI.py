import os
from dotenv import load_dotenv
from openai import OpenAI

#Load .env
load_dotenv()
client = OpenAI(
    api_key=os.getenv("OPENAI_API_KEY")
)

system_prompt = """
You are an expert, multilingual text extraction assistant 
Rules:
1. Keep answers concise
2. If information is missing, return null
3. Use production-grade best practices
"""





user_prompt = """
I want to extract list of grocery items from the text that has been generated by another OCR agent.

Requirements:
- Keep only the grocery item name
- Remove all other data
"""

response = client.chat.completions.create(
    model="gpt-4.1-mini",
    messages=[
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_prompt}
    ]
)

print(response.choices[0].message.content)




